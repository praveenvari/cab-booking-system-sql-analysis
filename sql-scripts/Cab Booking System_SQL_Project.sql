-- 2. Identify the most common reasons for trip cancellations from customer feedback. 
-- What actions can be taken to reduce cancellations?
select f.comments,count(b.bookingid) as NumberofCancellations  
from bookings b inner join feedback f on b.bookingid=f.bookingid
where b.status='cancelled'
group by f.comments 
order by NumberofCancellations;

-- 3. Find out whether shorter trips (low-distance) contribute significantly to revenue. 
-- Should the company encourage more short-distance rides?
select case when t.distancekm <= 6 then 'Short (<=6 KM)' 
			when t.distancekm <=10 then 'Medium (6-10 KM)' 
            else 'Long (>10 KM)'
            end as TripCategory
,count(*) as TotalTrips            
,sum(fare) as TotalRevenue
,round(sum(fare)/(select sum(t2.fare) from bookings b2 inner join tripdetails t2 on b2.bookingid=t2.bookingid)*100,2)
as RevenuePercent
from tripdetails t inner join bookings b on t.bookingid=b.bookingid
where b.status='completed'
group by TripCategory
order by TotalRevenue desc;

