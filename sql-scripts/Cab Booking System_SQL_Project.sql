-- 2. Predict which customers are likely to stop using the service based on their last booking date and frequency of rides. 
-- How can customer retention be improved?
select c.customerid,c.name,max(b.bookingdate) as LastBookingDate,count(b.bookingid) as frequency
,datediff(curdate(),max(b.bookingdate)) as DaysSinceLastBooking
 from customers c inner join bookings b on c.customerid=b.customerid
group by c.customerid,c.name
order by DaysSinceLastBooking desc;

