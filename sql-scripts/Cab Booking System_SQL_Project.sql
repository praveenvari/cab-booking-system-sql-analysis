--
-- Customer and Booking Analysis
--
use p_cab_booking;

-- 1. Identify customers who have completed the most bookings. 
-- What insights can you draw about their behavior?
select c.customerid, c.name, count(b.bookingid) as TotalCompleteBookings from customers c inner join bookings b 
on c.customerid=b.customerid where b.status = 'completed'
group by c.customerid, c.name order by  TotalCompleteBookings desc, c.customerid;

-- 2. Find customers who have canceled more than 30% of their total bookings. 
-- What could be the reason for frequent cancellations?
select c.customerid, c.name
, count(b.bookingid) as TotalBookings
, sum(case when b.status ='cancelled' then 1 else 0 end) as CancelledBookings 
, Round((sum(case when b.status ='cancelled' then 1 else 0 end)/count(b.bookingid)) *100) as CancelRate
from customers c inner join bookings b 
on c.customerid=b.customerid 
group by c.customerid, c.name 
having CancelRate > 30;

-- 3. Determine the busiest day of the week for bookings. 
-- How can the company optimize cab availability on peak days?
select dayname(b.bookingdate) as DayName,count(*) as TotalBookings  from bookings b 
group by DayName
order by TotalBookings desc limit 1;

-- 
-- Driver Performance & Efficiency
-- 
use p_cab_booking;

-- 1. Identify drivers who have received an average rating below 3.0 in the past three months. 
-- What strategies can be implemented to improve their performance?
select d.driverid,d.name, round(avg(f.rating),2) as AvgRating  
from feedback f inner join drivers d on f.driverid=d.driverid  
inner join bookings b on f.bookingid=b.bookingid
where b.bookingdate >= date_sub(now(),interval 3 month)
group by d.driverid, d.name  
having AvgRating <= 3.0
order by AvgRating;

-- 2. Find the top 5 drivers who have completed the longest trips in terms of distance. 
-- What does this say about their working patterns?
select d.driverid,d.name,max(t.distancekm ) as distancekm
from tripdetails t inner join bookings b on t.bookingid=b.bookingid
inner join drivers d on b.driverid=d.driverid
group by d.driverid, d.name  
order by t.distancekm desc limit 5;

-- 3. Identify drivers with a high percentage of canceled trips. 
-- Could this indicate driver unreliability?
select d.driverid,d.name
,count(b.bookingid) as TotalTrips
,SUM(case when b.status='Cancelled' then 1 else 0 end) as CancelledTrips
,(SUM(case when b.status='Cancelled' then 1 else 0 end)/count(b.bookingid))*100 as CancelRate
 from drivers d inner join bookings b on d.driverid=b.driverid
group by d.driverid,d.name
having CancelRate > 30
order by CancelledTrips desc,CancelRate desc;

